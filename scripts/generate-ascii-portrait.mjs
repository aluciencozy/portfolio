import { writeFile } from "node:fs/promises";
import sharp from "sharp";

const sourcePath = "scripts/assets/profile-cutout.png";
const outputPath = "app/_components/portfolio/ascii-portrait.ts";
const columns = 42;
const rows = 30;
const characterRamp = " .:-=+*#%@";

// Tuned around the transparent head-and-shoulders source. Keeping the crop here
// makes future portrait updates deliberate and the generated result repeatable.
const crop = { left: 150, top: 90, width: 724, height: 860 };

const { data } = await sharp(sourcePath)
  .extract(crop)
  .resize(columns, rows, { fit: "fill" })
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

const luminance = [];
const alpha = [];

for (let index = 0; index < columns * rows; index += 1) {
  const pixel = index * 4;
  luminance.push(
    (0.2126 * data[pixel] +
      0.7152 * data[pixel + 1] +
      0.0722 * data[pixel + 2]) /
      255,
  );
  alpha.push(data[pixel + 3] / 255);
}

const sample = (values, x, y) => {
  const safeX = Math.max(0, Math.min(columns - 1, x));
  const safeY = Math.max(0, Math.min(rows - 1, y));
  return values[safeY * columns + safeX];
};

const portrait = Array.from({ length: rows }, (_, y) => {
  let line = "";

  for (let x = 0; x < columns; x += 1) {
    const index = y * columns + x;
    const opacity = alpha[index];

    if (opacity < 0.08) {
      line += " ";
      continue;
    }

    const horizontalEdge =
      -sample(luminance, x - 1, y - 1) -
      2 * sample(luminance, x - 1, y) -
      sample(luminance, x - 1, y + 1) +
      sample(luminance, x + 1, y - 1) +
      2 * sample(luminance, x + 1, y) +
      sample(luminance, x + 1, y + 1);
    const verticalEdge =
      -sample(luminance, x - 1, y - 1) -
      2 * sample(luminance, x, y - 1) -
      sample(luminance, x + 1, y - 1) +
      sample(luminance, x - 1, y + 1) +
      2 * sample(luminance, x, y + 1) +
      sample(luminance, x + 1, y + 1);
    const edge = Math.min(1, Math.hypot(horizontalEdge, verticalEdge) * 1.4);
    const density =
      opacity * (0.08 + 0.46 * (1 - luminance[index]) + 0.46 * edge);
    const rampIndex = Math.min(
      characterRamp.length - 1,
      Math.floor(density * (characterRamp.length - 1)),
    );

    line += characterRamp[rampIndex];
  }

  return line;
});

const serializedPortrait = portrait
  .map((line) => `  ${JSON.stringify(line)},`)
  .join("\n");
const output = `// Generated by npm run generate:portrait. Do not edit by hand.\nexport const asciiPortrait = [\n${serializedPortrait}\n].join("\\n");\n`;

await writeFile(outputPath, output);
console.log(`Generated ${columns}x${rows} ASCII portrait at ${outputPath}`);
